    val gyroOdr: String? = null,
    val lowGRange: String? = null,
    val highGRange: String? = null,
    val gyroRange: String? = null,
    // Trigger config
    val autoTriggerEnabled: Boolean = false,
    val triggerAxis: String = "Z",
    val triggerCondition: String = "Deviation",
    val triggerThreshold: Float = 50f,
    val triggerDelayMs: Long = 200L,
    // UI config
    val timeWindowSec: Float = 5f,
    val filterEnabled: Boolean = false,
    val filterAlpha: Float = 0.2f,
    val chartTitle: String = "",
    val yAxisUnit: String = "",
    // Analysis features
    val showPeakForce: Boolean = false,
    val showImpulse: Boolean = false,
    val showPeriodDetection: Boolean = false,
    val showVelocityIntegration: Boolean = false,
    val showFreeFallDetection: Boolean = false,
    val is3dAirplaneMode: Boolean = false,
    // Mathematics Lab features
    val isMathMode: Boolean = false,
    val mathOperation: MathOperation? = null,
    val defaultSignalSource: SignalSource? = null,
    val defaultSecondSource: SignalSource? = null,
    val instructions: String = ""
)

